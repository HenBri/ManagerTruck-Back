-- Esquema inicial de ManagerTruck para PostgreSQL 14+.
-- Primero ejecutar 00-create-database.sql. Ejecutar este archivo solamente
-- en una base nueva/vacía. No migra datos desde MySQL.
-- Los ENUM de MySQL se representan como VARCHAR + CHECK para conservar
-- @Enumerated(EnumType.STRING) y permitir evolucionar valores sin recrear tipos.

CREATE TABLE company (
    company_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (company_id > 0),
    company_name VARCHAR(150) NOT NULL,
    company_nit VARCHAR(30),
    company_address VARCHAR(255),
    company_phone VARCHAR(25),
    company_status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (company_status IN ('ACTIVE','INACTIVE')),
    company_created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE user_table (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (user_id > 0),
    user_email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    user_name VARCHAR(100) NOT NULL,
    user_lastname VARCHAR(150) NOT NULL,
    user_ci VARCHAR(30),
    user_phone VARCHAR(25),
    user_status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (user_status IN ('ACTIVE','INACTIVE')),
    user_created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE role_table (
    role_id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (role_id > 0),
    role_name VARCHAR(50) NOT NULL UNIQUE,
    role_scope VARCHAR(8) NOT NULL CHECK (role_scope IN ('PLATFORM','COMPANY')),
    role_description VARCHAR(255),
    CONSTRAINT uq_role_id_scope UNIQUE (role_id, role_scope)
);

CREATE TABLE platform_user_role (
    user_id BIGINT NOT NULL,
    role_id SMALLINT NOT NULL,
    role_scope VARCHAR(8) NOT NULL DEFAULT 'PLATFORM' CHECK (role_scope = 'PLATFORM'),
    granted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_pur_user FOREIGN KEY (user_id) REFERENCES user_table(user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pur_role_scope FOREIGN KEY (role_id, role_scope) REFERENCES role_table(role_id, role_scope) ON DELETE RESTRICT
);
CREATE INDEX idx_pur_role ON platform_user_role(role_id, role_scope);

CREATE TABLE company_user (
    company_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    membership_status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (membership_status IN ('ACTIVE','INACTIVE')),
    joined_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (company_id, user_id),
    CONSTRAINT fk_cu_company FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_cu_user FOREIGN KEY (user_id) REFERENCES user_table(user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_membership_user ON company_user(user_id);

CREATE TABLE company_user_role (
    company_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    role_id SMALLINT NOT NULL,
    role_scope VARCHAR(8) NOT NULL DEFAULT 'COMPANY' CHECK (role_scope = 'COMPANY'),
    PRIMARY KEY (company_id, user_id, role_id),
    CONSTRAINT fk_cur_membership FOREIGN KEY (company_id, user_id) REFERENCES company_user(company_id, user_id) ON DELETE CASCADE,
    CONSTRAINT fk_cur_role_scope FOREIGN KEY (role_id, role_scope) REFERENCES role_table(role_id, role_scope) ON DELETE RESTRICT
);
CREATE INDEX idx_cur_role ON company_user_role(role_id, role_scope);

CREATE TABLE client (
    client_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (client_id > 0),
    company_id BIGINT NOT NULL,
    client_name VARCHAR(150) NOT NULL,
    client_ci VARCHAR(30),
    client_email VARCHAR(255),
    client_phone VARCHAR(25),
    client_address VARCHAR(255),
    client_state BOOLEAN NOT NULL DEFAULT TRUE,
    client_create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_client_tenant_id UNIQUE (company_id, client_id),
    CONSTRAINT fk_client_company FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE RESTRICT
);
CREATE INDEX idx_client_company_name ON client(company_id, client_name);

CREATE TABLE contract_table (
    contract_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (contract_id > 0),
    company_id BIGINT NOT NULL,
    client_id BIGINT NOT NULL,
    contract_amount DECIMAL(15,2) NOT NULL DEFAULT 0 CHECK (contract_amount >= 0),
    contract_date DATE NOT NULL,
    contract_description VARCHAR(255),
    contract_type VARCHAR(50),
    contract_state VARCHAR(10) NOT NULL DEFAULT 'DRAFT' CHECK (contract_state IN ('DRAFT','ACTIVE','COMPLETED','CANCELLED')),
    CONSTRAINT uq_contract_tenant_id UNIQUE (company_id, contract_id),
    CONSTRAINT fk_contract_client FOREIGN KEY (company_id, client_id) REFERENCES client(company_id, client_id) ON DELETE RESTRICT
);
CREATE INDEX idx_contract_client ON contract_table(company_id, client_id);

CREATE TABLE charge_table (
    charge_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (charge_id > 0),
    company_id BIGINT NOT NULL,
    contract_id BIGINT NOT NULL,
    charge_description VARCHAR(255),
    charge_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    charge_type VARCHAR(100),
    charge_state VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (charge_state IN ('PENDING','IN_TRANSIT','DELIVERED','CANCELLED')),
    CONSTRAINT uq_charge_tenant_id UNIQUE (company_id, charge_id),
    CONSTRAINT fk_charge_contract FOREIGN KEY (company_id, contract_id) REFERENCES contract_table(company_id, contract_id) ON DELETE RESTRICT
);
CREATE INDEX idx_charge_contract ON charge_table(company_id, contract_id);

CREATE TABLE container_table (
    container_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (container_id > 0),
    company_id BIGINT NOT NULL,
    charge_id BIGINT NOT NULL,
    container_code VARCHAR(30) NOT NULL,
    container_weight DECIMAL(12,3) CHECK (container_weight IS NULL OR container_weight >= 0),
    container_description VARCHAR(255),
    container_type VARCHAR(50),
    container_state VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE' CHECK (container_state IN ('AVAILABLE','LOADED','IN_TRANSIT','DELIVERED')),
    container_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_container_tenant_id UNIQUE (company_id, container_id),
    CONSTRAINT uq_container_company_code UNIQUE (company_id, container_code),
    CONSTRAINT fk_container_charge FOREIGN KEY (company_id, charge_id) REFERENCES charge_table(company_id, charge_id) ON DELETE RESTRICT
);
CREATE INDEX idx_container_charge ON container_table(company_id, charge_id);

CREATE TABLE partner_table (
    partner_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (partner_id > 0),
    company_id BIGINT NOT NULL,
    user_id BIGINT,
    partner_type VARCHAR(8) NOT NULL CHECK (partner_type IN ('PERSON','BUSINESS')),
    partner_name VARCHAR(150) NOT NULL,
    partner_document VARCHAR(30),
    partner_phone VARCHAR(25),
    partner_state VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (partner_state IN ('ACTIVE','INACTIVE')),
    CONSTRAINT uq_partner_tenant_id UNIQUE (company_id, partner_id),
    CONSTRAINT fk_partner_company FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_partner_membership FOREIGN KEY (company_id, user_id) REFERENCES company_user(company_id, user_id) ON DELETE RESTRICT
);
CREATE INDEX idx_partner_membership ON partner_table(company_id, user_id);

CREATE TABLE driver_table (
    driver_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (driver_id > 0),
    company_id BIGINT NOT NULL,
    user_id BIGINT,
    person_partner_id BIGINT,
    driver_name VARCHAR(150) NOT NULL,
    driver_ci VARCHAR(30),
    driver_phone VARCHAR(25),
    driver_license VARCHAR(40) NOT NULL,
    license_category VARCHAR(20),
    license_expiration DATE,
    driver_state VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (driver_state IN ('ACTIVE','INACTIVE')),
    CONSTRAINT uq_driver_tenant_id UNIQUE (company_id, driver_id),
    CONSTRAINT uq_driver_company_user UNIQUE (company_id, user_id),
    CONSTRAINT uq_driver_partner_person UNIQUE (company_id, person_partner_id),
    CONSTRAINT fk_driver_company FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE RESTRICT,
    CONSTRAINT fk_driver_membership FOREIGN KEY (company_id, user_id) REFERENCES company_user(company_id, user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_driver_partner_person FOREIGN KEY (company_id, person_partner_id) REFERENCES partner_table(company_id, partner_id) ON DELETE RESTRICT
);

CREATE TABLE truck_table (
    truck_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (truck_id > 0),
    company_id BIGINT NOT NULL,
    owner_partner_id BIGINT NOT NULL,
    truck_board VARCHAR(20) NOT NULL,
    truck_brand VARCHAR(50),
    truck_model VARCHAR(50),
    truck_chassis VARCHAR(50),
    truck_color VARCHAR(30),
    truck_year SMALLINT CHECK (truck_year IS NULL OR truck_year >= 0),
    truck_capacity DECIMAL(12,3) CHECK (truck_capacity IS NULL OR truck_capacity >= 0),
    truck_state VARCHAR(12) NOT NULL DEFAULT 'ACTIVE' CHECK (truck_state IN ('ACTIVE','MAINTENANCE','INACTIVE')),
    truck_create_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_truck_tenant_id UNIQUE (company_id, truck_id),
    CONSTRAINT uq_truck_company_board UNIQUE (company_id, truck_board),
    CONSTRAINT fk_truck_owner FOREIGN KEY (company_id, owner_partner_id) REFERENCES partner_table(company_id, partner_id) ON DELETE RESTRICT
);
CREATE INDEX idx_truck_owner ON truck_table(company_id, owner_partner_id);

CREATE TABLE truck_driver_assignment (
    assignment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (assignment_id > 0),
    company_id BIGINT NOT NULL,
    truck_id BIGINT NOT NULL,
    driver_id BIGINT NOT NULL,
    assigned_from TIMESTAMP NOT NULL,
    assigned_until TIMESTAMP,
    CONSTRAINT uq_assignment_tenant_id UNIQUE (company_id, assignment_id),
    CONSTRAINT uq_assignment_start UNIQUE (company_id, truck_id, driver_id, assigned_from),
    CONSTRAINT chk_assignment_dates CHECK (assigned_until IS NULL OR assigned_until > assigned_from),
    CONSTRAINT fk_tda_truck FOREIGN KEY (company_id, truck_id) REFERENCES truck_table(company_id, truck_id) ON DELETE RESTRICT,
    CONSTRAINT fk_tda_driver FOREIGN KEY (company_id, driver_id) REFERENCES driver_table(company_id, driver_id) ON DELETE RESTRICT
);
CREATE INDEX idx_assignment_driver ON truck_driver_assignment(company_id, driver_id);

CREATE TABLE auxiliary_provider (
    provider_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (provider_id > 0),
    company_id BIGINT NOT NULL,
    provider_kind VARCHAR(11) NOT NULL CHECK (provider_kind IN ('BUSINESS','INDEPENDENT')),
    provider_name VARCHAR(150) NOT NULL,
    provider_document VARCHAR(30),
    provider_phone VARCHAR(25),
    provider_email VARCHAR(255),
    provider_status VARCHAR(10) NOT NULL DEFAULT 'ACTIVE' CHECK (provider_status IN ('ACTIVE','INACTIVE')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_aux_provider_tenant_id UNIQUE (company_id, provider_id),
    CONSTRAINT fk_aux_provider_company FOREIGN KEY (company_id) REFERENCES company(company_id) ON DELETE RESTRICT
);
CREATE INDEX idx_aux_provider_name ON auxiliary_provider(company_id, provider_name);

CREATE TABLE journey_table (
    journey_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY CHECK (journey_id > 0),
    company_id BIGINT NOT NULL,
    container_id BIGINT NOT NULL,
    journey_origin VARCHAR(255) NOT NULL,
    journey_destination VARCHAR(255) NOT NULL,
    journey_start_date TIMESTAMP,
    journey_end_date TIMESTAMP,
    journey_description VARCHAR(255),
    journey_type VARCHAR(50),
    journey_state VARCHAR(12) NOT NULL DEFAULT 'PLANNED' CHECK (journey_state IN ('PLANNED','IN_PROGRESS','COMPLETED','CANCELLED')),
    execution_type VARCHAR(9) NOT NULL CHECK (execution_type IN ('PARTNER','AUXILIARY')),
    assignment_id BIGINT,
    auxiliary_provider_id BIGINT,
    auxiliary_truck_plate VARCHAR(20),
    auxiliary_driver_name VARCHAR(150),
    auxiliary_driver_license VARCHAR(40),
    auxiliary_reason VARCHAR(16) CHECK (auxiliary_reason IS NULL OR auxiliary_reason IN ('TRUCK_SHORTAGE','DRIVER_SHORTAGE','OTHER')),
    agreed_amount DECIMAL(15,2) CHECK (agreed_amount IS NULL OR agreed_amount >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_journey_tenant_id UNIQUE (company_id, journey_id),
    CONSTRAINT chk_journey_dates CHECK (journey_start_date IS NULL OR journey_end_date IS NULL OR journey_end_date >= journey_start_date),
    CONSTRAINT chk_journey_execution CHECK (
        (execution_type = 'PARTNER' AND assignment_id IS NOT NULL AND auxiliary_provider_id IS NULL
         AND auxiliary_truck_plate IS NULL AND auxiliary_driver_name IS NULL
         AND auxiliary_driver_license IS NULL AND auxiliary_reason IS NULL AND agreed_amount IS NULL)
        OR
        (execution_type = 'AUXILIARY' AND assignment_id IS NULL AND auxiliary_provider_id IS NOT NULL
         AND auxiliary_truck_plate IS NOT NULL AND BTRIM(auxiliary_truck_plate) <> ''
         AND auxiliary_driver_name IS NOT NULL AND BTRIM(auxiliary_driver_name) <> ''
         AND auxiliary_reason IS NOT NULL)
    ),
    CONSTRAINT fk_journey_container FOREIGN KEY (company_id, container_id) REFERENCES container_table(company_id, container_id) ON DELETE RESTRICT,
    CONSTRAINT fk_journey_assignment FOREIGN KEY (company_id, assignment_id) REFERENCES truck_driver_assignment(company_id, assignment_id) ON DELETE RESTRICT,
    CONSTRAINT fk_journey_provider FOREIGN KEY (company_id, auxiliary_provider_id) REFERENCES auxiliary_provider(company_id, provider_id) ON DELETE RESTRICT
);
CREATE INDEX idx_journey_container ON journey_table(company_id, container_id);
CREATE INDEX idx_journey_start ON journey_table(company_id, journey_start_date);
CREATE INDEX idx_journey_assignment ON journey_table(company_id, assignment_id);
CREATE INDEX idx_journey_provider ON journey_table(company_id, auxiliary_provider_id);
