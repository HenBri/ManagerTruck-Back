-- La carga y el contenedor de un flete deben pertenecer a su contrato.
-- Se verifica también el contenedor cuando se lo cambia de carga.
CREATE FUNCTION validate_freight_container() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM container_table c JOIN charge_table ch ON ch.charge_id=c.charge_id
    WHERE c.container_id=NEW.container_id AND ch.contract_id=NEW.contract_id
      AND NOT c.is_delete AND NOT ch.is_delete
  ) THEN
    RAISE EXCEPTION 'El contenedor % no pertenece al contrato % o esta eliminado', NEW.container_id, NEW.contract_id;
  END IF;
  IF TG_OP='UPDATE' AND (NEW.container_id IS DISTINCT FROM OLD.container_id OR NEW.contract_id IS DISTINCT FROM OLD.contract_id)
     AND EXISTS (SELECT 1 FROM journey_table j WHERE j.freight_id=NEW.freight_id AND j.state<>'PENDIENTE') THEN
    RAISE EXCEPTION 'No se puede cambiar el contenedor o contrato tras iniciar un viaje';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_validate_freight_container BEFORE INSERT OR UPDATE OF container_id, contract_id
ON freight_table FOR EACH ROW EXECUTE FUNCTION validate_freight_container();

-- Evita reasignar un contenedor a otro contrato si ya participa en fletes.
CREATE FUNCTION protect_container_charge() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF EXISTS (SELECT 1 FROM freight_table f WHERE f.container_id=NEW.container_id AND NOT f.is_delete)
     AND NEW.charge_id IS DISTINCT FROM OLD.charge_id THEN
    RAISE EXCEPTION 'Contenedor ya asignado a fletes; no se puede cambiar su carga';
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_protect_container_charge BEFORE UPDATE OF charge_id ON container_table
FOR EACH ROW EXECUTE FUNCTION protect_container_charge();

-- No permitir reubicar una carga entre contratos mientras sus contenedores se usan en fletes.
CREATE FUNCTION protect_charge_contract() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.contract_id IS DISTINCT FROM OLD.contract_id AND EXISTS (
    SELECT 1 FROM container_table c JOIN freight_table f ON f.container_id=c.container_id
    WHERE c.charge_id=OLD.charge_id AND NOT f.is_delete
 ) THEN RAISE EXCEPTION 'La carga contiene contenedores asignados a fletes'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_protect_charge_contract BEFORE UPDATE OF contract_id ON charge_table
FOR EACH ROW EXECUTE FUNCTION protect_charge_contract();

-- Reglas de disponibilidad: los intervalos programados DEBEN incluir ambas fechas.
-- Se utiliza un bloqueo por recurso para evitar carreras entre operaciones concurrentes.
-- Fletes cancelados, completados o eliminados no reservan recursos.
CREATE FUNCTION validate_freight_availability() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_conflict BIGINT;
BEGIN
  IF NEW.is_delete OR NEW.state IN ('COMPLETADO','CANCELADO') THEN RETURN NEW; END IF;
  IF (NEW.scheduled_departure IS NULL) <> (NEW.scheduled_arrival IS NULL) THEN
     RAISE EXCEPTION 'Ambas fechas programadas del flete deben informarse juntas';
  END IF;
  IF NEW.scheduled_departure IS NULL THEN RETURN NEW; END IF;
  -- bloqueos de transacción (los ids de recurso son distintos por tipo)
  PERFORM pg_advisory_xact_lock(4001, hashtext(NEW.container_id::text));
  IF NEW.truck_id IS NOT NULL THEN PERFORM pg_advisory_xact_lock(4002, hashtext(NEW.truck_id::text)); END IF;
  SELECT f.freight_id INTO v_conflict FROM freight_table f
   WHERE f.freight_id<>NEW.freight_id AND NOT f.is_delete
     AND f.state NOT IN ('CANCELADO','COMPLETADO')
     AND f.scheduled_departure IS NOT NULL AND f.scheduled_arrival IS NOT NULL
     AND tstzrange(f.scheduled_departure, f.scheduled_arrival,'[)') &&
         tstzrange(NEW.scheduled_departure, NEW.scheduled_arrival,'[)')
     AND (f.container_id=NEW.container_id OR
          (NEW.truck_id IS NOT NULL AND f.truck_id=NEW.truck_id) OR
          (NEW.auxiliary_truck_plate IS NOT NULL AND f.auxiliary_truck_plate=NEW.auxiliary_truck_plate))
   LIMIT 1;
  IF FOUND THEN RAISE EXCEPTION 'Recurso ya asignado al flete % en ese periodo', v_conflict; END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER trg_freight_availability BEFORE INSERT OR UPDATE OF
container_id,truck_id,auxiliary_truck_plate,scheduled_departure,scheduled_arrival,state,is_delete
ON freight_table FOR EACH ROW EXECUTE FUNCTION validate_freight_availability();

-- El viaje se crea al registrar el flete, sin conductor hasta que se programe.
-- El origen/destino se toman del contrato; por eso deben estar definidos.
CREATE FUNCTION create_journey_for_freight() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_origin VARCHAR(255); v_destination VARCHAR(255);
BEGIN
  SELECT origin_location,destination_location INTO v_origin,v_destination
  FROM contract_table WHERE contract_id=NEW.contract_id;
  IF v_origin IS NULL OR v_destination IS NULL THEN
    RAISE EXCEPTION 'Defina origen y destino del contrato antes de crear fletes';
  END IF;
  INSERT INTO journey_table(freight_id,journey_origin,journey_destination,
       planned_start_date,planned_end_date,state)
  VALUES(NEW.freight_id,v_origin,v_destination,
       NEW.scheduled_departure,NEW.scheduled_arrival,'PENDIENTE');
  RETURN NULL;
END $$;
CREATE TRIGGER trg_create_journey_for_freight AFTER INSERT ON freight_table
FOR EACH ROW EXECUTE FUNCTION create_journey_for_freight();

-- Al completar el viaje se completa el flete en la misma transacción.
-- Exige confirmación de entrega y conductor asignado / conductor auxiliar.
CREATE FUNCTION sync_freight_from_journey() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE v_freight freight_table%ROWTYPE; v_driver BIGINT;
BEGIN
 SELECT * INTO v_freight FROM freight_table WHERE freight_id=NEW.freight_id FOR UPDATE;
 IF NEW.state IN ('EN_PROCESO','COMPLETADO') AND v_freight.state='CANCELADO' THEN
   RAISE EXCEPTION 'No se puede iniciar o completar un flete cancelado';
 END IF;
 IF NEW.state='COMPLETADO' THEN
   IF NEW.delivery_confirmed_at IS NULL THEN
     RAISE EXCEPTION 'Debe confirmarse la entrega antes de completar el viaje';
   END IF;
   IF v_freight.truck_id IS NOT NULL THEN
     IF NEW.assignment_id IS NULL THEN RAISE EXCEPTION 'Asigne conductor al viaje'; END IF;
     SELECT a.driver_id INTO v_driver FROM truck_driver_assignment a
       WHERE a.assignment_id=NEW.assignment_id AND a.truck_id=v_freight.truck_id
         AND NOT a.is_delete AND a.state='ACTIVE'
         AND a.assigned_from <= COALESCE(NEW.journey_start_date,NEW.delivery_confirmed_at)
         AND (a.assigned_until IS NULL OR a.assigned_until >= COALESCE(NEW.journey_end_date,NEW.delivery_confirmed_at));
     IF NOT FOUND THEN RAISE EXCEPTION 'Asignacion de conductor no coincide con camion o periodo'; END IF;
   ELSIF NEW.auxiliary_driver_name IS NULL OR NEW.auxiliary_driver_license IS NULL THEN
     RAISE EXCEPTION 'Informe conductor y licencia del auxilio';
   END IF;
   IF NEW.journey_end_date IS NULL THEN NEW.journey_end_date:=NEW.delivery_confirmed_at; END IF;
   UPDATE freight_table SET state='COMPLETADO',actual_arrival=COALESCE(actual_arrival,NEW.delivery_confirmed_at)
   WHERE freight_id=NEW.freight_id AND state<>'CANCELADO';
 ELSIF NEW.state='EN_PROCESO' THEN
   UPDATE freight_table SET state='EN_PROCESO', actual_departure=COALESCE(actual_departure,NEW.journey_start_date,CURRENT_TIMESTAMP)
   WHERE freight_id=NEW.freight_id AND state='PENDIENTE';
 ELSIF NEW.state='CANCELADO' THEN
   UPDATE freight_table SET state='CANCELADO' WHERE freight_id=NEW.freight_id AND state<>'COMPLETADO';
 END IF;
 RETURN NEW;
END $$;
-- BEFORE permite completar fechas del viaje antes de guardarlo; el UPDATE al flete
-- activa el trigger existente que recalcula el contrato.
CREATE TRIGGER trg_sync_freight_from_journey BEFORE UPDATE OF state ON journey_table
FOR EACH ROW WHEN (OLD.state IS DISTINCT FROM NEW.state)
EXECUTE FUNCTION sync_freight_from_journey();

-- Impedir completar un flete directamente; el viaje es la fuente del cierre.
CREATE FUNCTION guard_freight_completion() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.state='COMPLETADO' AND OLD.state IS DISTINCT FROM 'COMPLETADO' THEN
   IF NOT EXISTS (SELECT 1 FROM journey_table j WHERE j.freight_id=NEW.freight_id
      AND j.delivery_confirmed_at IS NOT NULL AND
      (j.state='COMPLETADO' OR pg_trigger_depth()>1)) THEN
     RAISE EXCEPTION 'Complete el viaje y confirme entrega antes de completar el flete';
   END IF;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER trg_guard_freight_completion BEFORE UPDATE OF state ON freight_table
FOR EACH ROW EXECUTE FUNCTION guard_freight_completion();

-- Recalcular el estado del contrato tras cambios en fletes. La actualización
-- se ejecuta en la misma transacción; bloquear el contrato serializa fletes
-- concurrentes del mismo contrato. Los fletes CANCELADO no cuentan como completados.
CREATE FUNCTION refresh_contract_state(p_contract_id BIGINT)
RETURNS void LANGUAGE plpgsql AS $$
DECLARE v_state VARCHAR(20); v_total BIGINT; v_done BIGINT; v_started BIGINT;
BEGIN
  SELECT state INTO v_state FROM contract_table WHERE contract_id=p_contract_id FOR UPDATE;
  IF NOT FOUND OR v_state='CANCELADO' THEN RETURN; END IF;
  SELECT count(*), count(*) FILTER (WHERE state='COMPLETADO'),
         count(*) FILTER (WHERE state IN ('EN_PROCESO','COMPLETADO'))
    INTO v_total, v_done, v_started FROM freight_table
   WHERE contract_id=p_contract_id AND NOT is_delete AND state <> 'CANCELADO';
  UPDATE contract_table
     SET state=CASE WHEN v_total > 0 AND v_done=v_total THEN 'ENTREGADO'
                    WHEN v_started > 0 THEN 'EN_PROCESO'
                    ELSE 'PENDIENTE' END,
         actual_delivery_date=CASE WHEN v_total > 0 AND v_done=v_total
                                   THEN COALESCE(actual_delivery_date,CURRENT_TIMESTAMP)
                                   ELSE NULL END
   WHERE contract_id=p_contract_id;
END $$;

CREATE FUNCTION trg_refresh_contract_after_freight()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    PERFORM refresh_contract_state(OLD.contract_id);
  ELSIF TG_OP='UPDATE' THEN
    PERFORM refresh_contract_state(NEW.contract_id);
    IF OLD.contract_id IS DISTINCT FROM NEW.contract_id THEN
      PERFORM refresh_contract_state(OLD.contract_id);
    END IF;
  ELSE
    PERFORM refresh_contract_state(NEW.contract_id);
  END IF;
  RETURN NULL;
END $$;
CREATE TRIGGER trg_freight_contract_state
AFTER INSERT OR UPDATE OR DELETE ON freight_table
FOR EACH ROW EXECUTE FUNCTION trg_refresh_contract_after_freight();

