-- Herencia relacional (PK compartida): person -> partner_table / driver_table.
-- Sin tabla company ni relaciones multiempresa; sistema de una organización.
-- Todas las tablas contienen date_create, date_update, is_delete y state.
-- No ejecutar encima de tablas existentes: crear en una base vacía.
-- Cada flete transporta un contenedor y tiene exactamente un viaje (autocreado).
-- El pago al socio/chofer se realiza fuera del sistema: ENTREGADO no prueba pago.
